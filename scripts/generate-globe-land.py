#!/usr/bin/env python3
"""Generate local globe dots from public-domain Natural Earth land polygons.

Run from any directory: python3 scripts/generate-globe-land.py
No source data or network requests are needed by the browser at runtime.
"""
import json
import math
from pathlib import Path
from urllib.request import urlopen

SOURCE = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson'
SPACING = 1.2
COAST_SPACING = 0.84


def inside(x, y, ring):
    hit = False
    for index, (bx, by) in enumerate(ring):
        ax, ay = ring[index - 1]
        if (ay > y) != (by > y) and x < (bx - ax) * (y - ay) / (by - ay) + ax:
            hit = not hit
    return hit


def vector(lat, lon):
    lat, lon = math.radians(lat), math.radians(lon)
    return [math.cos(lat) * math.sin(lon), math.sin(lat), math.cos(lat) * math.cos(lon)]


def generate():
    with urlopen(SOURCE, timeout=30) as response:
        data = json.load(response)
    polygons = []
    for feature in data['features']:
        geometry = feature['geometry']
        parts = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
        for polygon in parts:
            xs, ys = zip(*polygon[0])
            polygons.append((min(xs), max(xs), min(ys), max(ys), polygon))

    land = []
    latitude, row = -82.0, 0
    while latitude < 84:
        step = SPACING / max(0.13, math.cos(math.radians(latitude)))
        longitude = -180 + (row % 2) * step / 2
        while longitude < 180:
            if any(a <= longitude <= b and c <= latitude <= d
                   and inside(longitude, latitude, polygon[0])
                   and not any(inside(longitude, latitude, hole) for hole in polygon[1:])
                   for a, b, c, d, polygon in polygons):
                land.extend([round(latitude, 3), round(longitude, 3)])
            longitude += step
        latitude += SPACING
        row += 1

    # Carry angular spacing across source vertices rather than emitting each
    # vertex, so heavily detailed coastlines do not create solid bright strokes.
    coastline = []
    seen = set()
    spacing = math.radians(COAST_SPACING)
    for *_, polygon in polygons:
        for ring in polygon:
            remaining = 0.0
            for index in range(1, len(ring)):
                lon1, lat1 = ring[index - 1]
                lon2, lat2 = ring[index]
                start, end = vector(lat1, lon1), vector(lat2, lon2)
                angle = math.acos(max(-1, min(1, sum(a * b for a, b in zip(start, end)))))
                if angle < 1e-10:
                    continue
                while remaining <= angle:
                    t = remaining / angle
                    point = [(math.sin((1 - t) * angle) * a + math.sin(t * angle) * b) / math.sin(angle)
                             for a, b in zip(start, end)]
                    lat = math.degrees(math.asin(max(-1, min(1, point[1]))))
                    lon = math.degrees(math.atan2(point[0], point[2]))
                    key = (round(lat, 2), round(lon, 2))
                    if key not in seen and lat > -82:
                        seen.add(key)
                        coastline.extend([round(lat, 3), round(lon, 3)])
                    remaining += spacing
                remaining -= angle

    target = Path(__file__).resolve().parents[1] / 'src/components/globe/globe-land.ts'
    target.write_text(
        '// Generated by scripts/generate-globe-land.py; do not edit manually.\n'
        '// Natural Earth 1:110m land; public domain.\n'
        f'// Source: {SOURCE}\n'
        '// Terms: https://www.naturalearthdata.com/about/terms-of-use/\n'
        '// Latitude, longitude pairs on a staggered 1.2-degree equal-area grid.\n'
        'export const LAND_COORDINATES: readonly number[] = ' + json.dumps(land, separators=(',', ':')) + ';\n'
        '// Independent coastline samples at 0.84-degree angular intervals.\n'
        'export const COAST_COORDINATES: readonly number[] = ' + json.dumps(coastline, separators=(',', ':')) + ';\n'
    )
    print(f'Generated {len(land) // 2} land dots and {len(coastline) // 2} coastline dots.')


if __name__ == '__main__':
    generate()
